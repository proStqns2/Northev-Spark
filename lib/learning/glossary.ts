export const GLOSSARY_TAGS = [...new Set(GLOSSARY.flatMap((entry) => entry.tags))].sort();

export function searchGlossary(query: string, tag: string | null = null): GlossaryEntry[] {
  const needle = query.trim().toLowerCase();
  return GLOSSARY.filter((entry) => {
    if (tag && !entry.tags.includes(tag)) return false;
    if (!needle) return true;
    return (
      entry.term.toLowerCase().includes(needle) ||
      entry.short.toLowerCase().includes(needle) ||
      entry.long.toLowerCase().includes(needle) ||
      entry.tags.some((t) => t.includes(needle))
    );
  });
}

export function glossaryEntry(term: string): GlossaryEntry | undefined {
  return GLOSSARY.find((entry) => entry.term.toLowerCase() === term.toLowerCase());
}
