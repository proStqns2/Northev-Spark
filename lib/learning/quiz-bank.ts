export const QUIZ_MODULES = [...new Set(QUIZ_BANK.map((question) => question.module))];

export function questionsFor(module: string, count = 8): QuizQuestion[] {
  const pool = QUIZ_BANK.filter((question) => question.module === module);
  if (!pool.length) return [];
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

export function questionsByIds(ids: string[]): QuizQuestion[] {
  return ids
    .map((id) => QUIZ_BANK.find((question) => question.id === id))
    .filter((question): question is QuizQuestion => Boolean(question));
}

