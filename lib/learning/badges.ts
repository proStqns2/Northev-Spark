export const BADGE_TIERS: Record<string, { label: string; color: string; ring: string }> = {
  bronze: { label: 'Bronze', color: '#d08b53', ring: 'rgba(208,139,83,0.35)' },
  argent: { label: 'Argent', color: '#b9c6d4', ring: 'rgba(185,198,212,0.35)' },
  or: { label: 'Or', color: '#ffc266', ring: 'rgba(255,194,102,0.4)' },
  platine: { label: 'Platine', color: '#a479ff', ring: 'rgba(164,121,255,0.4)' },
};

export function badgeById(id: string): Badge | undefined {
  return BADGES.find((badge) => badge.id === id);
}

export function badgesByTier(): Array<{ tier: string; label: string; items: Badge[] }> {
  return (['bronze', 'argent', 'or', 'platine'] as const).map((tier) => ({
    tier,
    label: BADGE_TIERS[tier].label,
    items: BADGES.filter((badge) => badge.tier === tier),
  }));
}
