export const FORMULA_CATEGORIES = [
  'continu',
  'alternatif',
  'réseaux',
  'puissance',
  'transitoire',
  'filtres',
] as const;

export const CATEGORY_LABEL: Record<string, string> = {
  continu: 'Courant continu',
  alternatif: 'Courant alternatif',
  réseaux: 'Réseaux linéaires',
  puissance: 'Puissance et énergie',
  transitoire: 'Régimes transitoires',
  filtres: 'Filtres et fréquence',
};

export function formulasByCategory(): Array<{ category: string; label: string; items: FormulaEntry[] }> {
  return FORMULA_CATEGORIES.map((category) => ({
    category,
    label: CATEGORY_LABEL[category],
    items: FORMULAS.filter((formula) => formula.category === category),
  }));
}

export function searchFormulas(query: string): FormulaEntry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return FORMULAS;
  return FORMULAS.filter(
    (formula) =>
      formula.title.toLowerCase().includes(needle) ||
      formula.expression.toLowerCase().includes(needle) ||
      formula.description.toLowerCase().includes(needle),
  );
}
